export const ARGS_STRESS: EvalCase[] = (() => {
  const apps = ["Discord", "VS Code", "Spotify", "Chrome", "Slack", "Notepad"];
  const variants: { u: (a: string) => string; note: string }[] = [
    { u: (a) => a, note: "bare" },
    { u: (a) => a.toUpperCase(), note: "caps" },
    { u: (a) => `please open ${a}`, note: "polite" },
  ];
  const out: EvalCase[] = [];
  for (const app of apps) {
    for (const v of variants) {
      out.push(
        S({
          id: "TBD",
          title: `${app} (${v.note})`,
          category: "args",
          tags: ["args-stress", app],
          turns: [U(v.u(app))],
          calls: [call("open_app", { app })],
          minCalls: 1,
        }),
      );
    }
  }
  return out;
})();

